
const pool = require("./postgres");

async function initializeHearingSchema() {
    const client = await pool.connect();

    try {
        await client.query("BEGIN");

        // 1. Hearing schedules
        await client.query(`
            CREATE TABLE IF NOT EXISTS hearings (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                case_id INTEGER NOT NULL,

                hearing_type TEXT NOT NULL,
                scheduled_at TIMESTAMPTZ NOT NULL,
                venue TEXT NOT NULL,

                status TEXT NOT NULL DEFAULT 'Scheduled'
                    CHECK (
                        status IN (
                            'Scheduled',
                            'Rescheduled',
                            'Cancelled',
                            'Completed'
                        )
                    ),

                notes TEXT DEFAULT '',

                created_by INTEGER NOT NULL,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (case_id)
                    REFERENCES cases(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (created_by)
                    REFERENCES users(id)
                    ON DELETE RESTRICT
            )
        `);

        // 2. Hearing attendance confirmations
        await client.query(`
            CREATE TABLE IF NOT EXISTS hearing_confirmations (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                hearing_id INTEGER NOT NULL,

                party_type TEXT NOT NULL
                    CHECK (
                        party_type IN (
                            'complainant',
                            'respondent'
                        )
                    ),

                recipient_name TEXT NOT NULL,
                recipient_email TEXT NOT NULL,

                token_hash CHAR(64) NOT NULL UNIQUE,

                status TEXT NOT NULL DEFAULT 'Pending'
                    CHECK (
                        status IN (
                            'Pending',
                            'Confirmed',
                            'Declined',
                            'Expired'
                        )
                    ),

                expires_at TIMESTAMPTZ NOT NULL,
                responded_at TIMESTAMPTZ,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (hearing_id)
                    REFERENCES hearings(id)
                    ON DELETE CASCADE,

                UNIQUE (hearing_id, party_type)
            )
        `);

        // 3. Hearing email notification history
        await client.query(`
            CREATE TABLE IF NOT EXISTS hearing_notifications (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                hearing_id INTEGER NOT NULL,

                party_type TEXT NOT NULL
                    CHECK (
                        party_type IN (
                            'complainant',
                            'respondent'
                        )
                    ),

                recipient_email TEXT NOT NULL,

                notification_type TEXT NOT NULL
                    CHECK (
                        notification_type IN (
                            'scheduled',
                            'rescheduled',
                            'cancelled',
                            'reminder'
                        )
                    ),

                delivery_status TEXT NOT NULL DEFAULT 'Pending'
                    CHECK (
                        delivery_status IN (
                            'Pending',
                            'Sent',
                            'Failed'
                        )
                    ),

                provider_message_id TEXT,
                error_message TEXT,

                sent_at TIMESTAMPTZ,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (hearing_id)
                    REFERENCES hearings(id)
                    ON DELETE CASCADE
            )
        `);

        // 4. Hearing schedule and action history
        await client.query(`
            CREATE TABLE IF NOT EXISTS hearing_history (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                hearing_id INTEGER NOT NULL,

                action TEXT NOT NULL,
                details JSONB DEFAULT '{}'::jsonb,

                performed_by INTEGER,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (hearing_id)
                    REFERENCES hearings(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (performed_by)
                    REFERENCES users(id)
                    ON DELETE SET NULL
            )
        `);

        // 5. Database indexes
        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_hearings_case
            ON hearings(case_id)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_hearings_schedule
            ON hearings(scheduled_at)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_hearings_status
            ON hearings(status)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_confirmations_hearing
            ON hearing_confirmations(hearing_id)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_notifications_hearing
            ON hearing_notifications(hearing_id)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_hearing_history
            ON hearing_history(hearing_id)
        `);

        await client.query("COMMIT");

        console.log("Hearing management tables are ready!");

    } catch (error) {
        await client.query("ROLLBACK");

        console.error(
            "Hearing schema initialization failed:",
            error
        );

        throw error;

    } finally {
        client.release();
    }
}

module.exports = initializeHearingSchema;
