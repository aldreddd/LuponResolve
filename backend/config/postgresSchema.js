
const pool = require("./postgres");

async function initializePostgresSchema() {
    const client = await pool.connect();

    try {
        await client.query("BEGIN");

        // 1. User accounts
        await client.query(`
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'resident',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);

        // 2. Resident complaints / cases
        await client.query(`
            CREATE TABLE IF NOT EXISTS cases (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                case_number TEXT UNIQUE,
                resident_id INTEGER,

                complainant_name TEXT NOT NULL,
                respondent_name TEXT NOT NULL,
                dispute_type TEXT NOT NULL,
                incident_details TEXT NOT NULL,

                status TEXT NOT NULL DEFAULT 'Pending Review',

                screening_status TEXT,
                screening_reasons TEXT,
                screening_warnings TEXT,
                screening_answers TEXT,

                secretary_notes TEXT DEFAULT '',
                case_stage TEXT DEFAULT 'Secretary Review',
                arbitration_applicable INTEGER DEFAULT 0,

                case_history TEXT DEFAULT '[]',
                case_proceedings TEXT DEFAULT '[]',

                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                resolution_outcome TEXT,
                resolution_notes TEXT DEFAULT '',
                resolved_at TIMESTAMP,
                resolved_by INTEGER,
                closure_notes TEXT DEFAULT '',
                closed_at TIMESTAMP,
                closed_by INTEGER,

                FOREIGN KEY (resident_id)
                    REFERENCES users(id)
                    ON DELETE RESTRICT
            )
        `);

            // Add respondent contact fields to existing cases.
            // IF NOT EXISTS makes this safe to run more than once.

            await client.query(`
                ALTER TABLE cases
                ADD COLUMN IF NOT EXISTS respondent_address TEXT
            `);

            await client.query(`
                ALTER TABLE cases
                ADD COLUMN IF NOT EXISTS respondent_email TEXT
            `);
                    // Guest complaint filing support
            // Remove the resident requirement from existing databases.
            await client.query(`
                ALTER TABLE cases
                DROP CONSTRAINT IF EXISTS cases_resident_id_not_null
            `);

            await client.query(`
                ALTER TABLE cases
                ALTER COLUMN resident_id DROP NOT NULL
            `);

            // Store complainant contact numbers.
            await client.query(`
                ALTER TABLE cases
                ADD COLUMN IF NOT EXISTS complainant_contact TEXT
            `);
            // Public case tracking: stores only the hash of the tracking secret.
            await client.query(`
                ALTER TABLE cases
                ADD COLUMN IF NOT EXISTS tracking_code_hash TEXT
            `);

        // 3. Lupon case assignments
        await client.query(`
            CREATE TABLE IF NOT EXISTS case_assignments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                case_id INTEGER NOT NULL,
                lupon_user_id INTEGER NOT NULL,
                assigned_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                UNIQUE(case_id, lupon_user_id),

                FOREIGN KEY (case_id)
                    REFERENCES cases(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (lupon_user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        `);

        // 4. Database indexes
        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_cases_resident
            ON cases(resident_id)
        `);

        await client.query(`
            CREATE INDEX IF NOT EXISTS idx_assignments_lupon
            ON case_assignments(lupon_user_id)
        `);

        await client.query("COMMIT");

        console.log("Neon PostgreSQL tables are ready!");

    } catch (error) {
        await client.query("ROLLBACK");
        console.error("PostgreSQL schema initialization failed:", error);
        throw error;

    } finally {
        client.release();
    }
}

module.exports = initializePostgresSchema;
